using System.Collections.Frozen;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json.Nodes;
using HsHelper.Core;
using HsHelper.Storage;

internal static class PublicHandMemoryStorageChecks
{
    public static IEnumerable<(string Name, Func<Task> Run)> Cases(string database)
    {
        yield return ("public hand memory keeps exact old decisions across later reveals and same-sequence withdrawal", () => Durable(database));
        yield return ("public hand memory codec freezes evidence and leaves legacy null JSON and hash unchanged", Codec);
        yield return ("malformed public hand memory cannot enter durable snapshot queues", () => Malformed(database));
        yield return ("new settled public hand facts after a gap are durably checkpointed before recording stops", () => PartialCheckpoint(database));
    }

    private static async Task Durable(string database)
    {
        var store = new SessionStore(database);
        var recorder = new SessionRecorder(store, new(null, "255790", 1));
        var original = Frame() with { StateVersion = 9, EventSequence = 9, PublicHandMemory = null };
        var oldJson = SnapshotCodec.Serialize(original);
        recorder.Observe(original, 9);
        recorder.Observe(Frame(), 20);
        // A later observation of the very same event sequence must not replace SV20.
        recorder.Observe(Frame() with { StateVersion = 21, PublicHandMemory = null }, 21);
        await recorder.CompleteAsync();
        var restarted = new SessionStore(database); await restarted.InitializeAsync();
        var points = await restarted.ListDecisionPointsAsync(original.MatchId, includeUnstable: true);
        var earlier = await restarted.GetDecisionSnapshotAsync(points.Single(point => point.StateVersion == 9).Id);
        var remembered = await restarted.GetDecisionSnapshotAsync(points.Single(point => point.StateVersion == 20).Id);
        var withdrawn = await restarted.GetDecisionSnapshotAsync(points.Single(point => point.StateVersion == 21).Id);
        Check(SnapshotCodec.Serialize(earlier!) == oldJson && earlier!.PublicHandMemory is null,
            "A later public identity backfilled the original old decision or changed its bytes.");
        Check(remembered!.PublicHandMemory?.Entries.Single() is { CardId: "PUBLIC_RETURNED", PublicAtSequence: 10, EnteredHandAtSequence: 15 } &&
            remembered.Entities[40].CardId is null && remembered.Entities[40].Cost is null &&
            PublicHandMemoryVisibility.Confirmed(remembered) is not null && withdrawn!.PublicHandMemory is null,
            "The stored memory was lost, promoted to a current hand entity or overwritten by a later same-sequence state.");
    }

    private static Task Codec()
    {
        // Generated by the immutable preview22 Core/Storage DLLs (3a9eb833), not this implementation.
        // Explicit synthetic input; the old codec's exact bytes and digest remain the compatibility oracle.
        var golden = File.ReadAllText(Path.Combine(AppContext.BaseDirectory, "Fixtures", "public-hand-memory-legacy.json"));
        const string goldenHash = "e73be69b4c597b7c671b271616f42415eb8aca402cff45a26e4daa60aa5ade68";
        Check(Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(golden))) == goldenHash &&
            SnapshotCodec.Serialize(SnapshotCodec.Deserialize(golden)) == golden &&
            SnapshotCodec.Deserialize(golden).PublicHandMemory is null,
            "New serialization changed the independent previous-release JSON bytes or invented public memory.");
        var source = new List<PublicHandMemoryEntry> { new(40, "PUBLIC_RETURNED", 2, "PLAY", 10, 15) };
        var warnings = new List<string> { "部分记录缺失；本条来自缺口后的新公开事实。" };
        var frame = Frame();
        frame = frame with { PublicHandMemory = new(frame.MatchId, frame.StateVersion, frame.EventSequence, 1, frame.PerspectiveSource,
            source, false, warnings, isSettled: true) };
        source.Clear(); warnings.Clear();
        var json = SnapshotCodec.Serialize(frame);
        var saved = SnapshotCodec.Deserialize(json);
        var memory = saved.PublicHandMemory!;
        Check(memory.Entries.Single().CardId == "PUBLIC_RETURNED" && memory.Warnings.Count == 1 && memory.IsSettled &&
            SnapshotCodec.Serialize(saved) == json, "Memory fields were omitted or mutable constructor input changed the frozen ledger.");
        Reject(() => ((IList<PublicHandMemoryEntry>)memory.Entries).Clear());
        Reject(() => ((IList<string>)memory.Warnings).Add("later"));
        var legacyJson = SnapshotCodec.Serialize(frame with { PublicHandMemory = null });
        Check(!legacyJson.Contains("\"PublicHandMemory\"", StringComparison.Ordinal), "A null optional field changed legacy JSON.");
        var legacyHash = SHA256.HashData(Encoding.UTF8.GetBytes(legacyJson));
        var legacy = SnapshotCodec.Deserialize(legacyJson);
        Check(legacy.PublicHandMemory is null && SnapshotCodec.Serialize(legacy) == legacyJson &&
            SHA256.HashData(Encoding.UTF8.GetBytes(SnapshotCodec.Serialize(legacy))).SequenceEqual(legacyHash),
            "An older record acquired false empty memory or changed its canonical hash.");
        var malformed = JsonNode.Parse(json)!;
        malformed["PublicHandMemory"]!["Entries"]![0] = null;
        try { SnapshotCodec.Deserialize(malformed.ToJsonString()); }
        catch (InvalidDataException) { return Task.CompletedTask; }
        throw new InvalidOperationException("Null memory entries entered a restored snapshot.");
    }

    private static Task Malformed(string database)
    {
        var frame = Frame();
        var recorder = new SessionRecorder(new SessionStore(database), new(null, "255790", 1));
        frame = frame with { PublicHandMemory = new(frame.MatchId, frame.StateVersion, frame.EventSequence, 1, frame.PerspectiveSource,
            [null!], true, []) };
        try { recorder.Observe(frame, 20); }
        catch (InvalidDataException)
        {
            Check(recorder.PendingCount == 0, "Malformed memory entered a pending durable batch.");
            return Task.CompletedTask;
        }
        throw new InvalidOperationException("Malformed memory was accepted for recording.");
    }

    private static async Task PartialCheckpoint(string database)
    {
        var store = new SessionStore(database);
        var recorder = new SessionRecorder(store, new(null, "255790", 1));
        GameSnapshot Partial(long version, IReadOnlyList<PublicHandMemoryEntry> entries)
        {
            var frame = Frame() with { MatchId = "public-memory-gap-storage", StateVersion = version, EventSequence = version,
                Quality = new(true, false, false, true, 0, ["合成输入缺口，整体质量不恢复。和独立公开身份分开核对。"]) };
            return frame with { PublicHandMemory = new(frame.MatchId, version, version, 1, frame.PerspectiveSource,
                entries, false, ["记录有遗漏。"], isSettled: true) };
        }
        recorder.Observe(Partial(30, []), 30); await recorder.FlushAsync();
        var entry = new PublicHandMemoryEntry(40, "PUBLIC_RETURNED", 2, "PLAY", 30, 31);
        recorder.Observe(Partial(31, [entry]), 31); await recorder.FlushAsync();
        var points = await store.ListDecisionPointsAsync("public-memory-gap-storage", includeUnstable: true);
        var point = points.SingleOrDefault(candidate => candidate.StateVersion == 31);
        Check(point is not null, "A settled newly reliable public identity after a gap was lost until CompleteAsync.");
        var saved = await store.GetDecisionSnapshotAsync(point!.Id);
        Check(!saved!.Quality.IsComplete && !saved.Quality.IsStable && PublicHandMemoryVisibility.Confirmed(saved)?.Entries.Single() == entry,
            "Saving a partial memory upgraded global quality or lost its independent public proof.");
        recorder.Observe(Partial(32, [entry]), 32); await recorder.FlushAsync();
        Check((await store.ListDecisionPointsAsync("public-memory-gap-storage", includeUnstable: true)).Count == points.Count,
            "Unchanged memory bindings created a checkpoint for every unrelated partial observation.");
    }

    private static GameSnapshot Frame()
    {
        var hidden = new EntitySnapshot(40, null, EntityKind.Card,
            new Dictionary<string, string> { ["ZONE"] = "HAND", ["CONTROLLER"] = "2" }.ToFrozenDictionary());
        var player = new EntitySnapshot(2, null, EntityKind.Player,
            new Dictionary<string, string> { ["PLAYER_ID"] = "1" }.ToFrozenDictionary());
        var opponent = new EntitySnapshot(3, null, EntityKind.Player,
            new Dictionary<string, string> { ["PLAYER_ID"] = "2" }.ToFrozenDictionary());
        var frame = new GameSnapshot("public-hand-memory-storage", 20, 20, 2, 1, 1, GamePhase.Main,
            new[] { hidden, player, opponent }.ToFrozenDictionary(entity => entity.Id), new(true, true, true, true, 0, []))
            { ClientBuild = "255790", PerspectiveSource = "manual" };
        return frame with { PublicHandMemory = new(frame.MatchId, 20, 20, 1, frame.PerspectiveSource,
            [new(40, "PUBLIC_RETURNED", 2, "PLAY", 10, 15)], true, [], isSettled: true) };
    }

    private static void Reject(Action action)
    {
        try { action(); }
        catch (NotSupportedException) { return; }
        throw new InvalidOperationException("Restored memory remained mutable.");
    }
    private static void Check(bool value, string message) { if (!value) throw new InvalidOperationException(message); }
}
